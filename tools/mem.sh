#!/bin/sh
# Скільки процесів і скільки пам'яті займає сервер разом із нащадками.
#   sh tools/mem.sh PID
# Запускайте, ПОКИ сервер під навантаженням (echo-bench працює в іншому терміналі).
# PSS (proportional set size) ділить спільні сторінки між процесами, що їх
# використовують, тому суму PSS можна чесно складати — на відміну від RSS.
[ $# -eq 1 ] || { echo "використання: $0 PID" >&2; exit 2; }
files=""
for p in "$1" $(pgrep -P "$1"); do files="$files /proc/$p/smaps_rollup"; done
# 2>/dev/null: нащадок міг завершитися, поки ми рахували
cat $files 2>/dev/null | awk '
    /^Rss:/ { n++; rss += $2 }
    /^Pss:/ { pss += $2 }
    END {
        printf "процесів: %d\n", n
        printf "сума PSS: %d КіБ   (чесна оцінка)\n", pss
        printf "сума RSS: %d КіБ   (завищена: спільні сторінки пораховано кілька разів)\n", rss
    }'
